create index if not exists history_access_overrides_target_idx on public.history_access_overrides (target_staff_id);
create index if not exists history_access_overrides_admin_idx on public.history_access_overrides (granted_by_admin_id);
create index if not exists history_access_overrides_active_idx
    on public.history_access_overrides (target_staff_id, expires_at)
    where revoked_at is null;

create table if not exists public.audit_logs (
    id bigint generated always as identity primary key,
    actor_staff_id uuid references public.staff_profiles(id) on delete set null,
    actor_role text not null,
    action text not null,
    entity_type text not null,
    entity_id text not null,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists audit_logs_actor_staff_id_idx on public.audit_logs (actor_staff_id);
create index if not exists audit_logs_created_at_idx on public.audit_logs (created_at desc);

create table if not exists public.daily_receipt_counters (
    receipt_date date primary key,
    last_seq integer not null default 0 check (last_seq >= 0)
);

-- ----------------------------------------------------------------------------
-- 7. Analytical Views (All explicitly WITH (security_invoker = true))
-- ----------------------------------------------------------------------------
create or replace view public.v_ward_occupancy
with (security_invoker = true) as
select
    r.id as room_id,
    r.room_code,
    r.room_name,
    r.ward_type,
    r.contagious_status,
    r.daily_rate,
    count(b.id)::integer as total_beds,
    count(a.id)::integer as occupied_beds,
    (count(b.id) - count(a.id))::integer as available_beds
from public.rooms r
join public.beds b on b.room_id = r.id and b.is_active = true
left join public.admissions a on a.bed_id = b.id and a.discharged_at is null
group by r.id, r.room_code, r.room_name, r.ward_type, r.contagious_status, r.daily_rate
order by r.room_code;

create or replace view public.v_active_pharmacy_inventory
with (security_invoker = true) as
select
    m.id as medication_id,
    mb.id as batch_id,
    m.drug_code,
    mb.batch_no,
    m.generic_name,
    m.dosage_form,
    m.unit_price,
    mb.stock_qty,
    m.low_stock_limit,
    mb.expiry_date,
    mb.status as batch_status,
    (mb.expiry_date - current_date)::integer as days_until_expiry,
    (mb.stock_qty < m.low_stock_limit) as is_low_stock,
    case
        when (mb.expiry_date - current_date) <= 0 then 'Expired / Blocked'
        when (mb.expiry_date - current_date) <= 30 then 'Expiring · Blocked'
        when (mb.expiry_date - current_date) <= 60 then 'Near Expiry'
        when mb.stock_qty < m.low_stock_limit then 'Low Stock'
        else 'In Stock'
    end as expiry_status
from public.medications m
join public.medication_batches mb
    on mb.medication_id = m.id
   and mb.status = 'Active'
order by m.generic_name, m.drug_code;

create or replace view public.v_doctor_availability
with (security_invoker = true) as
select
    d.id as doctor_id,
    d.full_name,
    d.specialty,
    d.consultation_fee,
    count(ap.id) filter (where ap.status = 'Active')::integer as active_outpatient_count,
    count(ad.id) filter (where ad.discharged_at is null)::integer as active_inpatient_count
from public.doctors d
left join public.appointments ap on ap.doctor_id = d.id and ap.status = 'Active'
left join public.admissions ad on ad.attending_doctor_id = d.id and ad.discharged_at is null
where d.is_active = true
group by d.id, d.full_name, d.specialty, d.consultation_fee
order by d.id;

create or replace view public.v_active_billing_queue
with (security_invoker = true) as
select
    bl.id as billing_ledger_id,
    bl.visit_type,
    bl.account_label,
    bl.origin_label,
    bl.clinical_note,
    bl.status,
    bl.or_number,
    case
        when bl.status = 'Promissory Note' then coalesce(bl.room_cost, 0)
        when bl.visit_type = 'Inpatient' and r.daily_rate is not null then round(r.daily_rate * ad.stay_days, 2)
        else 0::numeric(12,2)
    end as live_room_cost,
    case
        when bl.status = 'Promissory Note' then coalesce(bl.doctor_cost, 0)
        else bl.doctor_fee_snapshot
    end as live_doctor_cost,
    coalesce(sum(pi.subtotal), 0)::numeric(12,2) as live_pharmacy_cost,
    case
        when bl.status = 'Promissory Note' then coalesce(bl.settled_total, 0)
        else round(
            (case when bl.visit_type = 'Inpatient' and r.daily_rate is not null then r.daily_rate * ad.stay_days else 0 end)
            + bl.doctor_fee_snapshot
            + coalesce(sum(pi.subtotal), 0),
            2
        )
    end as live_estimated_total,
    bl.created_at
from public.billing_ledgers bl
left join public.admissions ad on ad.id = bl.admission_id
left join public.beds b on b.id = ad.bed_id
left join public.rooms r on r.id = b.room_id
left join public.prescription_items pi on pi.billing_ledger_id = bl.id
where bl.status in ('Active', 'Promissory Note')
group by
    bl.id, bl.visit_type, bl.account_label, bl.origin_label, bl.clinical_note,
    bl.status, bl.or_number, bl.room_cost, bl.doctor_cost, bl.settled_total,
    bl.doctor_fee_snapshot, r.daily_rate, ad.stay_days, bl.created_at
order by bl.created_at desc, bl.id desc;

create or replace view public.v_settlement_history
with (security_invoker = true) as
select
    bl.id as billing_ledger_id,
    bl.or_number,
    bl.visit_type,
    bl.account_label,
    bl.origin_label,
    bl.status,
    bl.room_cost,
    bl.doctor_cost,
    bl.pharmacy_cost,
    bl.gross_subtotal,
    bl.discount_amount,
    bl.surcharge_amount,
    bl.settled_total,
    bl.ward_released,
    bl.issued_at,
    bl.issued_by_role,
    bl.paid_at,
    bl.paid_by_role,
    coalesce(bl.paid_at, bl.issued_at) as effective_settled_at,
    coalesce(bl.paid_by_role, bl.issued_by_role) as effective_cashier_role
from public.billing_ledgers bl
where bl.status in ('Paid', 'Promissory Note')
order by coalesce(bl.paid_at, bl.issued_at) desc, bl.id desc;

create or replace view public.v_dashboard_kpis
with (security_invoker = true) as
select
    (select count(*)::integer from public.admissions where discharged_at is null) as active_inpatients,
    (select count(*)::integer from public.beds where is_active = true) as total_beds,
    (select count(*)::integer from public.admissions where discharged_at is null) as occupied_beds,
    (select count(*)::integer from public.v_active_pharmacy_inventory where is_low_stock = true) as low_stock_count,
    (select coalesce(sum(live_estimated_total), 0)::numeric(12,2) from public.v_active_billing_queue where status = 'Active') as unbilled_active_total;

create or replace view public.v_revenue_analytics
with (security_invoker = true) as
select
    coalesce(sum(settled_total) filter (where status = 'Paid'), 0)::numeric(12,2) as collected_paid_total,
    count(*) filter (where status = 'Paid')::integer as paid_count,
    coalesce(sum(settled_total) filter (where status = 'Promissory Note'), 0)::numeric(12,2) as promissory_unpaid_total,
    count(*) filter (where status = 'Promissory Note')::integer as promissory_count
from public.billing_ledgers;

