        movement_type in ('INITIAL_SEED', 'ADD_STOCK', 'CSV_RESTOCK', 'DISPENSE', 'EXPIRED_DISPOSAL')
    ),
    qty_delta integer not null check (qty_delta <> 0),
    balance_after integer not null check (balance_after >= 0),
    billing_ledger_id bigint references public.billing_ledgers(id) on delete restrict,
    note text,
    performed_by uuid references public.staff_profiles(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists stock_movements_batch_id_idx on public.stock_movements (batch_id);
create index if not exists stock_movements_ledger_id_idx on public.stock_movements (billing_ledger_id);
create index if not exists stock_movements_performed_by_idx on public.stock_movements (performed_by);

create table if not exists public.payment_events (
    id bigint generated always as identity primary key,
    billing_ledger_id bigint not null references public.billing_ledgers(id) on delete restrict,
    event_type text not null check (event_type in ('SETTLED_PAID', 'PROMISSORY_ISSUED', 'PROMISSORY_PAID')),
    amount numeric(12,2) not null check (amount >= 0),
    performed_by uuid references public.staff_profiles(id) on delete set null,
    performed_by_role text not null,
    created_at timestamptz not null default now()
