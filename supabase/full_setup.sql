create table if not exists public.history_access_overrides (
    id bigint generated always as identity primary key,
    target_staff_id uuid not null references public.staff_profiles(id) on delete cascade,
    granted_by_admin_id uuid not null references public.staff_profiles(id) on delete restrict,
    granted_at timestamptz not null default now(),
    expires_at timestamptz not null,
    revoked_at timestamptz,
    constraint history_override_window_chk check (expires_at > granted_at)
