begin;

-- Sequences for human-readable hospital identifiers
create sequence if not exists public.patient_mrn_seq start with 1 increment by 1;
create sequence if not exists public.otc_ticket_seq start with 1003 increment by 1;

-- ----------------------------------------------------------------------------
-- 1. Staff Profiles (linked 1:1 to Supabase auth.users)
-- ----------------------------------------------------------------------------
create table if not exists public.staff_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique,
    email text not null unique,
    full_name text not null,
    role text not null check (
        role in (
            'Hospital Administrator',
            'Front Desk & Admissions Staff',
            'Hospital Pharmacist',
            'Billing & Discharge Officer'
        )
    ),
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 2. Clinical Reference Catalogs: Doctors, Illnesses, Rooms, Beds
-- ----------------------------------------------------------------------------
create table if not exists public.doctors (
    id bigint generated always as identity primary key,
    full_name text not null unique,
    specialty text not null,
    consultation_fee numeric(10,2) not null check (consultation_fee >= 0),
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.illness_categories (
    category_name text primary key,
    contagious_status text not null check (contagious_status in ('Contagious', 'Non-Contagious')),
    suggested_doctor_id bigint not null references public.doctors(id) on delete restrict
);

create index if not exists illness_categories_suggested_doctor_idx
    on public.illness_categories (suggested_doctor_id);

create table if not exists public.rooms (
    id bigint generated always as identity primary key,
    room_code text not null unique,
    room_name text not null,
    ward_type text not null,
    contagious_status text not null check (contagious_status in ('Contagious', 'Non-Contagious')),
    daily_rate numeric(10,2) not null check (daily_rate > 0),
    created_at timestamptz not null default now()
);

create table if not exists public.room_allowed_illnesses (
    room_id bigint not null references public.rooms(id) on delete cascade,
    illness_category text not null references public.illness_categories(category_name) on delete restrict,
    primary key (room_id, illness_category)
);

create index if not exists room_allowed_illnesses_category_idx
    on public.room_allowed_illnesses (illness_category);

create table if not exists public.beds (
    id bigint generated by default as identity primary key,
    room_id bigint not null references public.rooms(id) on delete restrict,
    bed_label text not null unique,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create index if not exists beds_room_id_idx
    on public.beds (room_id);

-- ----------------------------------------------------------------------------
-- 3. Master Patient Registry
-- ----------------------------------------------------------------------------
create table if not exists public.patients (
    id bigint generated always as identity primary key,
    mrn text not null unique default (
        'PT-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.patient_mrn_seq')::text, 4, '0')
    ),
    full_name text not null check (char_length(trim(full_name)) >= 2),
    normalized_name text generated always as (lower(trim(full_name))) stored,
    created_at timestamptz not null default now()
);

create index if not exists patients_normalized_name_idx
    on public.patients (normalized_name);

-- ----------------------------------------------------------------------------
-- 4. Inpatient Admissions (IPD) & Outpatient Appointments (OPD)
-- ----------------------------------------------------------------------------
create table if not exists public.admissions (
    id bigint generated always as identity primary key,
    patient_id bigint not null references public.patients(id) on delete restrict,
    bed_id bigint not null references public.beds(id) on delete restrict,
    attending_doctor_id bigint not null references public.doctors(id) on delete restrict,
    contagious_status text not null check (contagious_status in ('Contagious', 'Non-Contagious')),
    illness_category text not null references public.illness_categories(category_name) on delete restrict,
    stay_days integer not null default 1 check (stay_days between 1 and 365),
    admitted_at timestamptz not null default now(),
    discharged_at timestamptz,
    admitted_by uuid references public.staff_profiles(id) on delete set null,
    constraint admissions_discharge_order_chk check (discharged_at is null or discharged_at >= admitted_at)
);

create index if not exists admissions_patient_id_idx on public.admissions (patient_id);
create index if not exists admissions_bed_id_idx on public.admissions (bed_id);
create index if not exists admissions_doctor_id_idx on public.admissions (attending_doctor_id);
create index if not exists admissions_illness_category_idx on public.admissions (illness_category);
create index if not exists admissions_admitted_by_idx on public.admissions (admitted_by);

-- Guarantee at most ONE active inpatient admission per physical bed at any time
create unique index if not exists admissions_one_active_per_bed_uniq
    on public.admissions (bed_id)
    where discharged_at is null;

create table if not exists public.appointments (
    id bigint generated always as identity primary key,
    patient_id bigint not null references public.patients(id) on delete restrict,
    doctor_id bigint not null references public.doctors(id) on delete restrict,
    appointment_date date not null default current_date,
    time_slot text not null check (
        time_slot in ('09:00 AM', '10:00 AM', '11:00 AM', '01:00 PM', '02:00 PM', '03:00 PM', '04:00 PM')
    ),
    status text not null default 'Active' check (status in ('Active', 'Settled', 'Cancelled')),
    settled_at timestamptz,
    booked_by uuid references public.staff_profiles(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists appointments_patient_id_idx on public.appointments (patient_id);
create index if not exists appointments_doctor_id_idx on public.appointments (doctor_id);
create index if not exists appointments_booked_by_idx on public.appointments (booked_by);
create index if not exists appointments_active_slot_idx
    on public.appointments (doctor_id, appointment_date, time_slot)
    where status = 'Active';

-- ----------------------------------------------------------------------------
-- 5. Central Pharmacy Catalog & Batch Lots
-- ----------------------------------------------------------------------------
create table if not exists public.medications (
    id bigint generated always as identity primary key,
    drug_code text not null unique check (char_length(trim(drug_code)) >= 3),
    generic_name text not null check (char_length(trim(generic_name)) >= 2),
    dosage_form text not null check (char_length(trim(dosage_form)) >= 2),
    unit_price numeric(10,2) not null check (unit_price > 0),
    low_stock_limit integer not null default 15 check (low_stock_limit >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.medication_batches (
    id bigint generated always as identity primary key,
    medication_id bigint not null references public.medications(id) on delete restrict,
    batch_no text not null check (char_length(trim(batch_no)) >= 2),
    stock_qty integer not null check (stock_qty >= 0),
    expiry_date date not null,
    status text not null default 'Active' check (status in ('Active', 'Disposed', 'Superseded')),
    disposed_at timestamptz,
    disposed_by uuid references public.staff_profiles(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists medication_batches_medication_id_idx on public.medication_batches (medication_id);
create index if not exists medication_batches_disposed_by_idx on public.medication_batches (disposed_by);
create index if not exists medication_batches_expiry_idx
    on public.medication_batches (expiry_date)
    where status = 'Active';

-- Guarantee at most ONE active physical lot per medication catalog item
create unique index if not exists medication_batches_one_active_uniq
    on public.medication_batches (medication_id)
    where status = 'Active';

-- ----------------------------------------------------------------------------
-- 6. Unified Billing Ledgers, Prescription Line Items & Immutable Audit Logs
-- ----------------------------------------------------------------------------
create table if not exists public.billing_ledgers (
    id bigint generated always as identity primary key,
    visit_type text not null check (visit_type in ('Inpatient', 'Outpatient', 'Walk-In OTC')),
    patient_id bigint references public.patients(id) on delete restrict,
    admission_id bigint references public.admissions(id) on delete restrict,
    appointment_id bigint references public.appointments(id) on delete restrict,
    walkin_ticket_code text unique,
    account_label text not null,
    origin_label text not null,
    clinical_note text not null default '',
    doctor_id bigint references public.doctors(id) on delete restrict,
    doctor_fee_snapshot numeric(10,2) not null default 0 check (doctor_fee_snapshot >= 0),
    status text not null default 'Active' check (status in ('Active', 'Promissory Note', 'Paid')),
    or_number text unique,
    room_cost numeric(12,2) check (room_cost is null or room_cost >= 0),
    doctor_cost numeric(12,2) check (doctor_cost is null or doctor_cost >= 0),
    pharmacy_cost numeric(12,2) check (pharmacy_cost is null or pharmacy_cost >= 0),
    gross_subtotal numeric(12,2) check (gross_subtotal is null or gross_subtotal >= 0),
    discount_amount numeric(12,2) check (discount_amount is null or discount_amount >= 0),
    surcharge_amount numeric(12,2) check (surcharge_amount is null or surcharge_amount >= 0),
    settled_total numeric(12,2) check (settled_total is null or settled_total >= 0),
    ward_released text,
    issued_at timestamptz,
    issued_by uuid references public.staff_profiles(id) on delete set null,
    issued_by_role text,
    paid_at timestamptz,
    paid_by uuid references public.staff_profiles(id) on delete set null,
    paid_by_role text,
    created_at timestamptz not null default now(),
    constraint billing_ledgers_source_exclusivity_chk check (
        (visit_type = 'Inpatient'   and admission_id is not null and appointment_id is null and walkin_ticket_code is null)
        or
        (visit_type = 'Outpatient'  and admission_id is null and appointment_id is not null and walkin_ticket_code is null)
        or
        (visit_type = 'Walk-In OTC' and admission_id is null and appointment_id is null and walkin_ticket_code is not null)
    ),
    constraint billing_ledgers_accounting_chk check (
        status = 'Active'
        or (
            or_number is not null
            and room_cost is not null
            and doctor_cost is not null
            and pharmacy_cost is not null
            and gross_subtotal is not null
            and discount_amount is not null
            and surcharge_amount is not null
            and settled_total is not null
            and issued_at is not null
            and gross_subtotal = round(room_cost + doctor_cost + pharmacy_cost, 2)
            and discount_amount <= round(gross_subtotal + surcharge_amount, 2)
            and settled_total = round(gross_subtotal - discount_amount + surcharge_amount, 2)
            and (status <> 'Paid' or paid_at is not null)
            and (status <> 'Promissory Note' or paid_at is null)
        )
    )
);

create index if not exists billing_ledgers_patient_id_idx on public.billing_ledgers (patient_id);
create index if not exists billing_ledgers_admission_id_idx on public.billing_ledgers (admission_id);
create index if not exists billing_ledgers_appointment_id_idx on public.billing_ledgers (appointment_id);
create index if not exists billing_ledgers_doctor_id_idx on public.billing_ledgers (doctor_id);
create index if not exists billing_ledgers_issued_by_idx on public.billing_ledgers (issued_by);
create index if not exists billing_ledgers_paid_by_idx on public.billing_ledgers (paid_by);
create index if not exists billing_ledgers_status_created_idx on public.billing_ledgers (status, created_at desc);

create unique index if not exists billing_ledgers_admission_uniq
    on public.billing_ledgers (admission_id)
    where admission_id is not null;

create unique index if not exists billing_ledgers_appointment_uniq
    on public.billing_ledgers (appointment_id)
    where appointment_id is not null;

create table if not exists public.prescription_items (
    id bigint generated always as identity primary key,
    billing_ledger_id bigint not null references public.billing_ledgers(id) on delete restrict,
    medication_id bigint not null references public.medications(id) on delete restrict,
    batch_id bigint not null references public.medication_batches(id) on delete restrict,
    drug_name_snapshot text not null,
    dosage_form_snapshot text not null,
    qty integer not null check (qty > 0),
    unit_price_snapshot numeric(10,2) not null check (unit_price_snapshot > 0),
    subtotal numeric(12,2) generated always as (round((qty * unit_price_snapshot)::numeric, 2)) stored,
    dispensed_by uuid references public.staff_profiles(id) on delete set null,
    dispensed_at timestamptz not null default now()
);

create index if not exists prescription_items_ledger_id_idx on public.prescription_items (billing_ledger_id);
create index if not exists prescription_items_medication_id_idx on public.prescription_items (medication_id);
create index if not exists prescription_items_batch_id_idx on public.prescription_items (batch_id);
create index if not exists prescription_items_dispensed_by_idx on public.prescription_items (dispensed_by);

create table if not exists public.stock_movements (
